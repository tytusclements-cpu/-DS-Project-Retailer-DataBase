CREATE TABLE Brands (
    brand_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    brand_name     VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_brands PRIMARY KEY (brand_id),
    CONSTRAINT uq_brands_name UNIQUE (brand_name)
);

CREATE TABLE Product_Types (
    product_type_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    type_name       VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_product_types PRIMARY KEY (product_type_id),
    CONSTRAINT uq_product_types_name UNIQUE (type_name)
);

CREATE TABLE Vendors (
    vendor_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vendor_name    VARCHAR2(150) NOT NULL,
    phone          VARCHAR2(30),
    email          VARCHAR2(150),
    street_address VARCHAR2(200),
    city           VARCHAR2(100),
    state          VARCHAR2(50),
    postal_code    VARCHAR2(20),
    CONSTRAINT pk_vendors PRIMARY KEY (vendor_id)
);

CREATE TABLE Stores (
    store_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    store_name     VARCHAR2(150) NOT NULL,
    street_address VARCHAR2(200),
    city           VARCHAR2(100),
    state          VARCHAR2(50),
    postal_code    VARCHAR2(20),
    CONSTRAINT pk_stores PRIMARY KEY (store_id)
);

CREATE TABLE Customers (
    customer_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    first_name     VARCHAR2(100) NOT NULL,
    last_name      VARCHAR2(100) NOT NULL,
    email          VARCHAR2(150),
    phone          VARCHAR2(30),
    street_address VARCHAR2(200),
    city           VARCHAR2(100),
    state          VARCHAR2(50),
    postal_code    VARCHAR2(20),
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE Products (
    product_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    product_name    VARCHAR2(150) NOT NULL,
    brand_id        NUMBER NOT NULL,
    product_type_id NUMBER NOT NULL,
    unit_price      NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_products PRIMARY KEY (product_id),
    CONSTRAINT fk_products_brand
        FOREIGN KEY (brand_id) REFERENCES Brands (brand_id),
    CONSTRAINT fk_products_type
        FOREIGN KEY (product_type_id) REFERENCES Product_Types (product_type_id),
    CONSTRAINT ck_products_price CHECK (unit_price >= 0)
);

-- Current stock for each product at each store.
CREATE TABLE Inventory (
    store_id   NUMBER NOT NULL,
    product_id NUMBER NOT NULL,
    quantity   NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT pk_inventory PRIMARY KEY (store_id, product_id),
    CONSTRAINT fk_inventory_store
        FOREIGN KEY (store_id) REFERENCES Stores (store_id),
    CONSTRAINT fk_inventory_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT ck_inventory_quantity CHECK (quantity >= 0)
);

-- A sale is a checkout transaction at a physical store.
CREATE TABLE Sales (
    sale_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    store_id     NUMBER NOT NULL,
    customer_id  NUMBER,
    sale_date    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_sales PRIMARY KEY (sale_id),
    CONSTRAINT fk_sales_store
        FOREIGN KEY (store_id) REFERENCES Stores (store_id),
    CONSTRAINT fk_sales_customer
        FOREIGN KEY (customer_id) REFERENCES Customers (customer_id)
);

-- Products and quantities included in each sale.
CREATE TABLE Sale_Items (
    sale_id      NUMBER NOT NULL,
    product_id   NUMBER NOT NULL,
    quantity     NUMBER(10) NOT NULL,
    unit_price   NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_sale_items PRIMARY KEY (sale_id, product_id),
    CONSTRAINT fk_sale_items_sale
        FOREIGN KEY (sale_id) REFERENCES Sales (sale_id),
    CONSTRAINT fk_sale_items_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT ck_sale_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_sale_items_price CHECK (unit_price >= 0)
);

-- Online orders placed by customers.
CREATE TABLE Web_Orders (
    order_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id   NUMBER NOT NULL,
    order_date    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    order_status  VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    CONSTRAINT pk_web_orders PRIMARY KEY (order_id),
    CONSTRAINT fk_web_orders_customer
        FOREIGN KEY (customer_id) REFERENCES Customers (customer_id)
);

CREATE TABLE Web_Order_Items (
    order_id     NUMBER NOT NULL,
    product_id   NUMBER NOT NULL,
    quantity     NUMBER(10) NOT NULL,
    unit_price   NUMBER(10,2) NOT NULL,
    CONSTRAINT pk_web_order_items PRIMARY KEY (order_id, product_id),
    CONSTRAINT fk_web_order_items_order
        FOREIGN KEY (order_id) REFERENCES Web_Orders (order_id),
    CONSTRAINT fk_web_order_items_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT ck_web_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_web_items_price CHECK (unit_price >= 0)
);

-- Reorders sent to vendors to replenish store inventory.
CREATE TABLE Reorders (
    reorder_id    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    vendor_id     NUMBER NOT NULL,
    store_id      NUMBER NOT NULL,
    reorder_date  TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    reorder_status VARCHAR2(30) DEFAULT 'Pending' NOT NULL,
    CONSTRAINT pk_reorders PRIMARY KEY (reorder_id),
    CONSTRAINT fk_reorders_vendor
        FOREIGN KEY (vendor_id) REFERENCES Vendors (vendor_id),
    CONSTRAINT fk_reorders_store
        FOREIGN KEY (store_id) REFERENCES Stores (store_id)
);

CREATE TABLE Reorder_Items (
    reorder_id   NUMBER NOT NULL,
    product_id   NUMBER NOT NULL,
    quantity     NUMBER(10) NOT NULL,
    CONSTRAINT pk_reorder_items PRIMARY KEY (reorder_id, product_id),
    CONSTRAINT fk_reorder_items_reorder
        FOREIGN KEY (reorder_id) REFERENCES Reorders (reorder_id),
    CONSTRAINT fk_reorder_items_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT ck_reorder_items_quantity CHECK (quantity > 0)
);

-- Shipments received for a reorder.
CREATE TABLE Shipments (
    shipment_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    reorder_id    NUMBER NOT NULL,
    shipment_date TIMESTAMP,
    shipment_status VARCHAR2(30) DEFAULT 'In Transit' NOT NULL,
    CONSTRAINT pk_shipments PRIMARY KEY (shipment_id),
    CONSTRAINT fk_shipments_reorder
        FOREIGN KEY (reorder_id) REFERENCES Reorders (reorder_id)
);

CREATE TABLE Shipment_Items (
    shipment_id NUMBER NOT NULL,
    product_id  NUMBER NOT NULL,
    quantity    NUMBER(10) NOT NULL,
    CONSTRAINT pk_shipment_items PRIMARY KEY (shipment_id, product_id),
    CONSTRAINT fk_shipment_items_shipment
        FOREIGN KEY (shipment_id) REFERENCES Shipments (shipment_id),
    CONSTRAINT fk_shipment_items_product
        FOREIGN KEY (product_id) REFERENCES Products (product_id),
    CONSTRAINT ck_shipment_items_quantity CHECK (quantity > 0)
);